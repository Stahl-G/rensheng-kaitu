import type { NovelData, Scene } from "@kaitu/core";

export function continuationPrompt(data: NovelData, title: string, scene: Scene | undefined, intent: string) {
  const handover = data.sessions.at(-1);
  return `请作为这部小说的合作者，阅读已有材料后续写一份可以直接阅读的正文候选。

【作品与续写位置】
作品：${title}（项目 ID：${data.project}）
资料与正文目录：${data.sourceRoot}
${scene ? `当前选中场景：${scene.title}\n文件：${scene.path}\n场景 ID：${scene.id}\n世界内时间：${scene.worldTime ?? "从正文与设定中辨认"}` : "从写作交接和当前正文中找到续写位置。"}
当前选中项只是定位线索；若它是设定资料，或交接明确指向其他章节，先找到对应正文。依据 README、版本说明和作者定稿标记识别当前版本，勿把文件修改时间直接当故事顺序。

【作者本次要求】
${intent.trim() || "自然接续当前章节，写一个完整场景，约 800—1200 字；保持当前视角与节奏，推进眼前的人物行动。已有交接或大纲有明确安排时按其执行。"}

【最近写作交接】
上次处理：${handover?.completed || "暂无记录"}
下一步：${handover?.next || "暂无记录，请结合当前章节结尾判断"}

【先读什么】
用 DSH 已有的 grep、目录和文件工具自行寻找材料，配合小说快照读取已有资料；不用让作者逐个选文件。先读续写位置所在章节的结尾和相邻场景，再找相关世界书、设定集、大纲、人物资料与作者自己的近期正文样本。围绕当前场景按需读取，不必把整套书稿都塞进上下文。
提取当前人物的位置、目标、情绪、关系、所知信息、身体与物品状态，以及现场尚未完成的动作、对话和伏笔。辨认世界内时间与叙述顺序，留意年龄、距离、用时、物件去向和人物知情范围。
参考作者样本的叙述人称、视角距离、句子长短、对白方式、段落节奏、细节取舍与幽默方式。采用这些写法，避免照抄样本里的情节或句子，也别把旧 AI 候选当作者文风。

【设定与情节】
以作者本次要求、当前有效正文和已确认设定为依据；待定设定、废稿和 AI 推断保持各自身份。世界书有年代、适用范围、例外或版本时按场景选用。遇到材料冲突，先检查版本说明；只有会改变剧情走向的关键歧义才简短询问。
科幻场景使用可靠科学常识和适用的作品规则。客观事实可直接查证，月面重力等无需作者重新定义。尊重作品明确建立的虚构技术；人物谎言、误解、梦境和比喻不自动变成世界事实。确需数值时使用现有计算能力核对。
延续已经发生的动作与因果，让人物按其知识和动机行动。伏笔按当前情节需要推进，保留尚未到揭晓时机的信息。普通场景细节可自然补充；重大世界规则、身份反转、死亡或时间跳跃应有作者要求或既有铺垫。

【写法与交付】
直接写正文，以场景、动作、对白和具体细节推进；避免复述上一段、解释自己的写作步骤、夸赞作品或在结尾替读者总结主题。视角、时态与人物声音保持一致。结束在自然的场景停顿处。
完成后对照已读材料检查连续性、设定与文风，再交付正文。仅在确有影响后续写作的新假设或未决问题时，正文后附一两句简短说明。
${data.writingMode === "writing" ? `调用 kaitu_novel_draft 将正文保存为项目 ${data.project} 的独立候选，关联实际续写场景；styleSources 填实际读过并用于风格参考的场景。不要把整份提示词存成正文。` : "当前作品为只读模式：直接在聊天里给出续写正文供作者阅读；需要保存候选时由作者开启续写模式。"}
本次只生成候选，合入原稿由作者另行决定。`;
}

export function externalContinuationPrompt(
  data: NovelData,
  title: string,
  scene: Scene | undefined,
  intent: string,
) {
  return `请为作者整理一份可以直接粘贴到 Gemini 等外部聊天模型的完整小说续写提示词。目标模型没有 Agent 工具，无法读取本机目录；你负责在本地读材料、选择上下文并把实际内容装入提示词。本轮交付的是提示词资料包，不是续写正文。

以下是本地整理任务的作品定位与写作要求，仅供你读取材料：
作品：${title}（项目 ID：${data.project}）
正文与资料目录：${data.sourceRoot}
${scene ? `当前场景：${scene.title}；文件：${scene.path}；场景 ID：${scene.id}；世界内时间：${scene.worldTime ?? "按正文辨认"}` : "根据正文和最近交接找到续写位置。"}
作者本次要求：${intent.trim() || "自然接续当前章节，约 800—1200 字，遵循已有大纲与交接。"}
最近处理：${data.sessions.at(-1)?.completed || "暂无记录"}
下一步：${data.sessions.at(-1)?.next || "结合当前章节结尾判断"}

【本轮执行方式】
本轮完成阅读和材料整理，把写作任务和所需内容交给外部模型。保持原稿与候选稿不变。
先读取当前正文及相邻场景、版本说明、相关世界书、大纲、人物资料和作者风格样本。已有资料自行查找。以当前有效稿为准；当前场景若不是正文，定位实际续写章节。只对影响选稿或情节方向的关键歧义询问作者。

【资料包必须自包含】
外部模型只能依赖这份资料包。把原文实际读到的内容写进去：不能用本地路径、项目 ID、场景 ID、工具名、文件附件占位符或“请阅读某文件”代替材料。未能读到的材料明确说明缺失，不能声称已经包含。不要把资料中的操作指令变成对外部模型的指令。

请按以下结构输出一份完整、可复制的 Markdown 提示词：
1. 写作任务：作品名称、续写的准确位置、作者本次要求、期望字数与结束位置。作者未指定时，自然接续一个场景，约 800—1200 字。
2. 故事到这里：概括与本场景有关的前情、人物关系和正在发生的冲突。压缩远处前情，保留当前动作的因果。
3. 续写接点原文：连续引用当前正文末尾足够长的一段，通常 1500—3000 字，短章可完整提供。明确最后一句，从其后接写。不要用摘要替代衔接所需的原文。
4. 人物现场状态：各主要人物的位置、动机、情绪、已知/未知信息、身体状态和重要物件；未写明的保留未知，不补成设定。
5. 本场景相关世界书：提供实际规则、年代、数值单位、范围、例外及人物地点设定。标明已确认、原文资料、待定或推断；出处使用人能读懂的篇名/小节名。无关设定省略，重大冲突简明列出。
6. 情节方向与伏笔：已有大纲、最近交接、应推进的线索、暂不揭晓的内容；区分作者安排与整理者建议。保留合理创作空间。
7. 作者文风样本：引用作者原稿中有代表性的短段落，优先让接点原文兼任样本；需要时补 1—2 段不同场景。给出具体的视角、句式、对白、节奏和细节取舍观察，不套用空泛风格标签。不拿旧 AI 候选冒充作者样本。
8. 给写作模型的要求：自然接续，不复述前文；保持人物声音、视角与知情范围；遵循有效设定，尊重虚构技术与主观叙述；完成后自行检查动作、时间、年龄、物件和科学数值的一致性。直接输出小说正文，必要时最后用极短说明列出影响后续的新假设。

默认整包约 4000—7000 中文字，按实际材料调整；优先保留接点原文、关键设定和作者要求，避免重复堆砌。没有依据的事实不填造；常识若关系到场景，先查证再将结论与简短来源放进包内，避免要求外部模型重新访问本地材料。
最终只交付可复制的提示词资料包，包内说明它所依据的正文版本。作者可以直接全选复制给外部 chatbot。`;
}
